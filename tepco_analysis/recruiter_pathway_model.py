"""大学別リクルーター接触後の採用経路の分岐（主観的シナリオモデル）。

注意: 東電建築職の実測分岐率は見つかっていない。以下の値はすべて仮置きで、
low/mid/high の3シナリオの幅として示す。経路は重複所属あり（例: インターン経由かつ
評価共有あり）。各条件付き確率の母集団は STEPS の説明列に明記し、単一の内定率には統合しない。
"""

# (キー, 母集団と条件, low, mid, high, 根拠の種類)
STEPS = [
    ("apply_intern", "リクルーター接触者(建築・マイページ登録済) → 建築インターン応募", 0.15, 0.35, 0.60, "仮置き"),
    ("attend_intern", "建築インターン応募者 → 参加（定員30名、応募多数時は書類選考）", 0.25, 0.50, 0.85, "定員は公式・倍率は不明"),
    ("early_after_intern", "インターン参加者 → 早期選考/ジョブマッチング等の案内", 0.20, 0.50, 0.85, "他技術職の個別証言のみ"),
    ("share_eval", "個別面談者 → 人物評価・接触記録の社内共有", 0.20, 0.50, 0.80, "制度未確認・仮置き"),
    ("share_to_benefit", "評価共有を受けた者 → 選考上の実質的優遇（省略・優先等）", 0.02, 0.10, 0.30, "証拠なし・仮置き"),
    ("first_choice_shift", "第一志望を明言した学生 → リクルーターの扱いが目に見えて変わる", 0.05, 0.20, 0.40, "本件メールでは変化観測されず"),
]

# 行動別に「接触→インターン参加」までの寄与だけを比較（内定率は算出しない）
ACTIONS = {
    "未応募のまま締切": {"apply": 0.0},
    "建築コースに応募": {"apply": 1.0},
    "他コースに応募": {"apply": 1.0, "arch_link": 0.5},  # 建築部門との接点が弱まる仮定
}


def main():
    print("== 条件付き確率（主観的シナリオ: low / mid / high） ==")
    for k, desc, lo, mid, hi, src in STEPS:
        print(f"{desc}\n    {lo:.0%} / {mid:.0%} / {hi:.0%}   [{src}]")

    print("\n== 行動別: 建築インターン参加→早期案内まで到達する可能性（参考の積、内定率ではない） ==")
    att = STEPS[1][2:5]
    early = STEPS[2][2:5]
    for name, a in ACTIONS.items():
        vals = [a["apply"] * at * e * a.get("arch_link", 1.0) for at, e in zip(att, early)]
        print(f"{name:12s} " + " / ".join(f"{v:.0%}" for v in vals))
    print("\n本選考の内定率: 算出不能（建築職の応募者数・採用数・倍率が未確認）")


if __name__ == "__main__":
    main()
